#!/usr/bin/env python3
"""
scripts/rule_generator.py — benchmark rule sets of any size, in iptables format.

Usage:  python3 scripts/rule_generator.py N            ->  rules/config_a_N.rules
        python3 scripts/rule_generator.py 10 100 1000  ->  all three

Every rule set has the same structure as the hand-made 10-rule set:
  FW_FORWARD : rule 1 (bastion SSH accept), -j FILTER_DROP, -j ALLOW, -j DROP (= miss)
  FILTER_DROP: rules 2-3
  ALLOW      : rules 4..N
and the benchmark packets (UDP 10.35.5.203:40000 -> 10.35.4.4) always match:
  BEST   port 80   = rule 4            (first rule in ALLOW)
  MIDDLE port 5500 = rule (4+N)//2     (N=10: 7,  N=100: 52,  N=1000: 502)
  WORST  port 9900 = rule N            (last rule)
  MISS   port 9999 = no rule -> DROP
For N=10 the output is exactly the hand-made rule set. For larger N, filler rules
(realistic TCP/UDP/multiport/source-specific accepts on ports 20000+) are added;
none of them can match a benchmark packet (wrong port, protocol or source).
The file is loaded as config A (config_a_setup.sh load N) and translated into the
BPF rules for B0/B1/B2 by scripts/rule_compiler.py, so all configs are identical.
"""
import os
import sys

FORWARD = ["-s 10.8.50.180/32 -p tcp -m tcp --dport 22 -j ACCEPT"]          # rule 1
FILTER_DROP = ["-s 192.168.100.0/24 -j DROP",                               # rule 2
               "-p tcp -m tcp --dport 22 -s 10.0.0.0/8 -j DROP"]            # rule 3
BEST   = "-p udp -m udp --dport 80 -j ACCEPT"
MIDDLE = "-p udp -m udp --dport 5500 -j ACCEPT"
WORST  = "-p udp -m udp --dport 9900 -j ACCEPT"
BEFORE_MIDDLE = ["-p tcp -m multiport --ports 80,443,5201 -j ACCEPT",       # web + iperf3 (TCP)
                 "-p udp -m multiport --ports 53,5001 -j ACCEPT"]           # DNS + old pktgen port
AFTER_MIDDLE  = ["-p icmp -j ACCEPT",                                       # ping
                 "-p udp -m udp --dport 5201 -j ACCEPT"]                    # iperf3 UDP mode
TEST_PORTS = {80, 5500, 9900, 9999, 40000}


def fillers(count, start_port):
    """Realistic accept rules that never match a benchmark packet."""
    out, port = [], start_port
    for i in range(count):
        kind = i % 4
        if kind == 0:
            out.append(f"-p tcp -m tcp --dport {port} -j ACCEPT"); port += 1
        elif kind == 1:
            out.append(f"-p udp -m udp --dport {port} -j ACCEPT"); port += 1
        elif kind == 2:
            out.append(f"-p tcp -m multiport --ports {port},{port + 1} -j ACCEPT"); port += 2
        else:   # source-specific: benchmark source 10.35.5.203 is never in 172.16.0.0/12
            out.append(f"-s 172.16.{(i // 4) % 256}.0/24 -p udp -m udp --dport {port} -j ACCEPT"); port += 1
    assert not TEST_PORTS & set(range(start_port, port)), "filler port collides with a test port"
    return out, port


def generate(n):
    if n < 10:
        raise SystemExit("N must be >= 10 (the base rule set has 10 rules)")
    mid = (4 + n) // 2                                  # rule number of MIDDLE
    n_before = mid - 4 - 1 - len(BEFORE_MIDDLE)         # fillers between rule 6 and MIDDLE
    n_after = n - mid - len(AFTER_MIDDLE) - 1           # fillers between rule 9-ish and WORST
    f_before, port = fillers(n_before, 20000)
    f_after, _ = fillers(n_after, port)
    allow = [BEST] + BEFORE_MIDDLE + f_before + [MIDDLE] + AFTER_MIDDLE + f_after + [WORST]
    rules = len(FORWARD) + len(FILTER_DROP) + len(allow)
    assert rules == n, (rules, n)
    assert allow.index(MIDDLE) + 4 == mid and allow.index(WORST) + 4 == n

    lines = [f"# rules/config_a_{n}.rules — generated by scripts/rule_generator.py {n}",
             f"# {n} rules: BEST port 80 = rule 4, MIDDLE port 5500 = rule {mid}, "
             f"WORST port 9900 = rule {n}, MISS port 9999 = DROP",
             "*filter", ":FW_FORWARD - [0:0]", ":FILTER_DROP - [0:0]", ":ALLOW - [0:0]"]
    lines += [f"-A FW_FORWARD {r}" for r in FORWARD]
    lines += ["-A FW_FORWARD -j FILTER_DROP", "-A FW_FORWARD -j ALLOW", "-A FW_FORWARD -j DROP"]
    lines += [f"-A FILTER_DROP {r}" for r in FILTER_DROP]
    lines += [f"-A ALLOW {r}" for r in allow]
    lines.append("COMMIT")
    return "\n".join(lines) + "\n", mid


def main():
    if len(sys.argv) < 2:
        print(__doc__); sys.exit(1)
    os.makedirs("rules", exist_ok=True)
    for arg in sys.argv[1:]:
        n = int(arg)
        text, mid = generate(n)
        path = f"rules/config_a_{n}.rules"
        with open(path, "w") as f:
            f.write(text)
        print(f"{path}: {n} rules (best=4, middle={mid}, worst={n})")


if __name__ == "__main__":
    main()
